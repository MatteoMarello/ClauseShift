"""Pilot 1b analysis (PILOT_PROTOCOL.md addendum, post hoc): psychometric functions around the cutoff.

P_sat(delta) = share of items whose prediction equals the label the item would have if the condition held.
95% percentile bootstrap over base cases (2,000). Resolution per side as defined in the addendum.
Outputs project_anomaly/results/pilot1b_results.json, PILOT1B_TABLES.md and figures/psychometric.png
"""

import json
import sys
from collections import defaultdict
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[2]
RES = ROOT / "project_anomaly/results"
sys.path.insert(0, str(Path(__file__).resolve().parent))
from run_models import CHECKPOINTS  # noqa: E402

B = 2000
items = [json.loads(line) for line in open(RES / "psychometric_probes.jsonl")]
TH_TAGS = ["rel-0.50", "rel-0.25", "rel-0.10", "rel-0.05", "rel-0.02", "unit-1", "rel+0.00", "unit+1", "rel+0.02",
           "rel+0.05", "rel+0.10", "rel+0.25", "rel+0.50"]
DATE_TAGS = [f"day{d:+d}" for d in (-365, -90, -30, -7, -2, -1, 0, 1, 2, 7, 30, 90, 365)]


def curve(sat: dict, tags: list, rng) -> dict:
    """sat: base -> {tag: 0/1}. Returns P_sat per tag with CI."""
    bases = sorted(sat)
    M = np.array([[sat[b][t] for t in tags] for b in bases], float)
    boots = M[rng.integers(0, len(bases), size=(B, len(bases)))].mean(axis=1)
    return {t: {"p_sat": float(M[:, j].mean()), "ci95": [float(np.percentile(boots[:, j], 2.5)),
                                                         float(np.percentile(boots[:, j], 97.5))]}
            for j, t in enumerate(tags)} | {"_n": len(bases)}


def side_resolution(c: dict, ordered_below: list, ordered_above: list) -> dict:
    """ordered_* : tags from nearest to farthest. Resolution = nearest tag from which the criterion holds at all
    farther tags on that side; None if it never holds."""
    def first_stable(tags, ok):
        for k in range(len(tags)):
            if all(ok(c[t]["p_sat"]) for t in tags[k:]):
                return tags[k]
        return None
    return {"below": first_stable(ordered_below, lambda p: p <= 0.1),
            "above": first_stable(ordered_above, lambda p: p >= 0.9)}


def main():
    rng = np.random.default_rng(0)
    results = {}
    for model in CHECKPOINTS:
        preds = {json.loads(line)["id"]: json.loads(line)["pred"]
                 for line in open(RES / f"predictions/pilot1b__{model}.jsonl")}
        sat = defaultdict(lambda: defaultdict(dict))
        for r in items:
            sat[(r["kind"], r["family"])][r["base"]][r["tag"]] = int(preds[r["id"]] == r["sat_label"])
        results[model] = {}
        for (kind, fam), cells in sorted(sat.items()):
            tags = TH_TAGS if kind == "threshold" else DATE_TAGS
            c = curve(cells, tags, rng)
            if kind == "threshold":
                below = ["unit-1", "rel-0.02", "rel-0.05", "rel-0.10", "rel-0.25", "rel-0.50"]
                above = ["unit+1", "rel+0.02", "rel+0.05", "rel+0.10", "rel+0.25", "rel+0.50"]
            else:
                below = DATE_TAGS[5::-1]
                above = DATE_TAGS[7:]
            c["_resolution"] = side_resolution(c, below, above)
            vals = [c[t]["p_sat"] for t in tags]
            c["_monotone"] = bool(all(vals[k] <= vals[k + 1] + 1e-9 for k in range(len(vals) - 1)))
            results[model][f"{kind}/{fam}"] = c
    json.dump(results, open(RES / "pilot1b_results.json", "w", newline="\n"), indent=2)

    L = ["# Pilot 1b tables (post hoc; generated by `project_anomaly/scripts/analyze_pilot1b.py`)", "",
         "P(satisfied reading) by signed distance from the cutoff; 30 base cases per cell. Ideal reader: 0 at and "
         "below the cutoff, 1 above it. Thresholds: `rel±r` = r × cutoff (rounded to the unit, ≥ 1 unit), `unit±1` "
         "= one unit (1 year / 1 credit / €5,000). Resolution = nearest distance from which P_sat stays ≤ 0.1 "
         "(below) or ≥ 0.9 (above) at all farther distances.", ""]
    for kind, tags in (("threshold", TH_TAGS), ("date", DATE_TAGS)):
        L += [f"## {kind}", "", "| model | family | " + " | ".join(tags) + " | monotone | resolution below / above |",
              "|" + "---|" * (len(tags) + 4)]
        for model, byg in results.items():
            for g, c in byg.items():
                if not g.startswith(kind):
                    continue
                r = c["_resolution"]
                L.append(f"| {model} | {g.split('/')[1]} | " + " | ".join(f"{c[t]['p_sat']:.2f}" for t in tags)
                         + f" | {c['_monotone']} | {r['below']} / {r['above']} |")
        L.append("")
    (RES / "PILOT1B_TABLES.md").write_text("\n".join(L) + "\n")
    print("\n".join(L))
    plot(results)


def plot(results):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    fams = ["vehicles", "enrollment", "research_funding"]
    colors = {"vehicles": "#4C72B0", "enrollment": "#DD8452", "research_funding": "#55A868"}
    fig, axes = plt.subplots(2, 2, figsize=(11, 7), sharey=True)
    for col, model in enumerate(["ft_nli-deberta-v3-xsmall_paired_s0", "ft_nli-deberta-v3-xsmall_unpaired_s0"]):
        for row, (kind, tags) in enumerate((("threshold", TH_TAGS), ("date", DATE_TAGS))):
            ax = axes[row, col]
            x = np.arange(len(tags))
            for fam in fams:
                c = results[model][f"{kind}/{fam}"]
                y = [c[t]["p_sat"] for t in tags]
                lo = [c[t]["ci95"][0] for t in tags]
                hi = [c[t]["ci95"][1] for t in tags]
                ax.plot(x, y, marker="o", ms=3.5, color=colors[fam], label=fam)
                ax.fill_between(x, lo, hi, color=colors[fam], alpha=0.12, linewidth=0)
            zero = tags.index("rel+0.00" if kind == "threshold" else "day+0")
            ax.step([x[0], zero + 0.5, x[-1]], [0, 1, 1], where="post", color="0.3", ls="--", lw=1, label="ideal")
            ax.axvline(zero, color="0.7", lw=0.8)
            ax.set_xticks(x)
            ax.set_xticklabels([t.replace("rel", "").replace("day", "") for t in tags], rotation=60, fontsize=7)
            ax.set_title(f"{model.replace('ft_', '').replace('_s0', '')} — {kind}", fontsize=9)
            ax.set_xlabel("signed distance (fraction of cutoff / units)" if kind == "threshold" else "days from cutoff",
                          fontsize=8)
            if col == 0:
                ax.set_ylabel("P(satisfied reading)", fontsize=8)
            ax.set_ylim(-0.03, 1.03)
    axes[0, 0].legend(fontsize=7, frameon=False, loc="upper left")
    fig.tight_layout()
    out = ROOT / "project_anomaly/figures"
    out.mkdir(exist_ok=True)
    fig.savefig(out / "psychometric.png", dpi=160)


if __name__ == "__main__":
    main()
