"""Exploratory (post hoc, after the addendum-2 test): accuracy on date-decisive test items by whether the case date
and the cutoff fall in the same calendar year, per training group (stored registered predictions, seeds 0-2), and the
corresponding statistics of the training data. No inference.

Cross-year, not-after items are those where a year-blind (month-and-day) comparison gives the wrong answer for a
date before the cutoff. Outputs project_anomaly/results/year_blindness.json and YEAR_BLINDNESS.md
"""

import contextlib
import dataclasses
import datetime as dt
import io
import json
import sys
from collections import defaultdict
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "src"))
sys.path.insert(0, str(ROOT / "research_next/scripts"))
with contextlib.redirect_stdout(io.StringIO()):
    from program_fingerprint import SPECS  # noqa: E402

from clauseshift.generator import gold_label  # noqa: E402

GROUPS = {"nli_paired": "ft_nli-deberta-v3-xsmall_paired_s{}", "nli_unpaired": "ft_nli-deberta-v3-xsmall_unpaired_s{}",
          "nli_op_holdout (no date_cross in training)": "ft_nli-deberta-v3-xsmall_op_holdout_s{}",
          "generic_paired": "ft_deberta-v3-xsmall_paired_s{}", "generic_unpaired": "ft_deberta-v3-xsmall_unpaired_s{}"}
CELLS = [("same", "after"), ("same", "not_after"), ("cross", "after"), ("cross", "not_after")]
B = 2000


def date_items(split):
    out = []
    for it in map(json.loads, open(ROOT / f"data/{split}.jsonl")):
        spec, case = SPECS[it["id"]]
        if spec.date_cutoff is None or case.date is None:
            continue
        cut, val = spec.date_cutoff, case.date
        sat = gold_label(spec, dataclasses.replace(case, date=cut + dt.timedelta(days=1)))[0]
        if sat == gold_label(spec, dataclasses.replace(case, date=cut))[0]:
            continue
        out.append({"id": it["id"], "pair_id": it["pair_id"], "label": it["label"], "operator": it["operator"],
                    "cell": ("same" if val.year == cut.year else "cross", "after" if val > cut else "not_after"),
                    "md_correct": ((val.month, val.day) > (cut.month, cut.day)) == (val > cut)})
    return out


def main():
    rng = np.random.default_rng(0)
    res = {"training_data": {}, "test": {}}
    for split in ("train", "dev", "test"):
        items = date_items(split)
        by = defaultdict(lambda: defaultdict(int))
        for r in items:
            g = "date_cross" if r["operator"] == "date_cross" else "other_operators"
            by[g]["n"] += 1
            by[g]["month_day_comparison_correct"] += r["md_correct"]
            by[g]["_".join(r["cell"])] += 1
        res["training_data" if split == "train" else f"{split}_data"] = {k: dict(v) for k, v in by.items()}
    test = date_items("test")
    pairs = sorted({r["pair_id"] for r in test})
    pid = np.array([pairs.index(r["pair_id"]) for r in test])
    draws = [np.bincount(rng.integers(0, len(pairs), len(pairs)), minlength=len(pairs))[pid] for _ in range(B)]
    for g, pat in GROUPS.items():
        corr = np.zeros(len(test))
        per_seed = {}
        for s in range(3):
            P = {r["id"]: r["pred"] for r in map(json.loads, open(ROOT / f"results/predictions/{pat.format(s)}/test.jsonl"))}
            c = np.array([P[r["id"]] == r["label"] for r in test], float)
            corr += c / 3
            per_seed[s] = {"_".join(cell): float(c[[r["cell"] == cell for r in test]].mean()) for cell in CELLS}
        res["test"][g] = {"per_seed": per_seed}
        for cell in CELLS:
            m = np.array([r["cell"] == cell for r in test])
            boots = [(w * corr * m).sum() / (w * m).sum() for w in draws]
            res["test"][g]["_".join(cell)] = {"accuracy": float(corr[m].mean()), "n_items": int(m.sum()),
                                             "ci95": [float(np.percentile(boots, 2.5)), float(np.percentile(boots, 97.5))]}
    json.dump(res, open(ROOT / "project_anomaly/results/year_blindness.json", "w", newline="\n"), indent=2)
    L = ["# Year blindness on the test split (exploratory, post hoc; generated by "
         "`project_anomaly/scripts/year_blindness.py`)", "",
         "Date-decisive test items, accuracy averaged over seeds 0–2 (95% cluster-bootstrap CI over minimal pairs). "
         "`cross / not_after` = the case date is in an earlier year but later in the calendar than the cutoff, the "
         "only cell where a comparison of month and day alone gives the wrong answer for a date before the cutoff.", "",
         "| Training group | same / after | same / not_after | cross / after | cross / not_after | cross / not_after per seed |",
         "|---|---|---|---|---|---|"]
    for g, r in res["test"].items():
        cell = lambda k: f"{r[k]['accuracy']:.3f} [{r[k]['ci95'][0]:.2f}, {r[k]['ci95'][1]:.2f}] (n={r[k]['n_items']})"  # noqa: E731
        L.append(f"| {g} | " + " | ".join(cell("_".join(c)) for c in CELLS) + " | "
                 + ", ".join(f"{r['per_seed'][s]['cross_not_after']:.2f}" for s in range(3)) + " |")
    L += ["", "Training data (date-decisive items): share on which comparing month and day alone gives the correct "
               "answer.", "", "| Split | Operator group | n | month-day correct | cells |", "|---|---|---|---|---|"]
    for split in ("training_data", "dev_data", "test_data"):
        for g, d in res[split].items():
            cells = ", ".join(f"{k}={v}" for k, v in d.items() if k not in ("n", "month_day_comparison_correct"))
            L.append(f"| {split} | {g} | {d['n']} | {d['month_day_comparison_correct'] / d['n']:.3f} | {cells} |")
    (ROOT / "project_anomaly/results/YEAR_BLINDNESS.md").write_text("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
