"""Pilot 1 analysis exactly as fixed in PILOT_PROTOCOL.md.

Accuracy by position x form; DiD(form) = [acc(eq,form) - acc(eq,same)] - [acc(plus,form) - acc(plus,same)];
percentile bootstrap over base cases (2,000 resamples). Validity: acc(plus,form) >= 0.70 and acc(minus,form) >= 0.70.
Output: project_anomaly/results/pilot1_results.json and PILOT1_TABLES.md
"""

import json
import sys
from collections import defaultdict
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[2]
RES = ROOT / "project_anomaly/results"
sys.path.insert(0, str(Path(__file__).resolve().parent))
from run_models import CHECKPOINTS  # noqa: E402

B, SEED = 2000, 0
items = {json.loads(line)["id"]: json.loads(line) for line in open(RES / "boundary_probes.jsonl")}


def table(model: str):
    preds = {json.loads(line)["id"]: json.loads(line)["pred"] for line in open(RES / f"predictions/pilot1__{model}.jsonl")}
    # correct[(kind, family)][base][(pos, form)] = 0/1
    correct = defaultdict(lambda: defaultdict(dict))
    for i, r in items.items():
        correct[(r["kind"], r["family"])][r["base"]][(r["position"], r["form"])] = int(preds[i] == r["label"])
    return correct


def summarise(cells: dict, rng):
    """cells: base -> {(pos, form): 0/1}. Returns accuracies, DiDs with 95% CI, validity."""
    bases = sorted(cells)
    forms = sorted({f for b in bases for (_, f) in cells[b]}, key=["same", "reorder", "words"].index)
    keys = [(p, f) for p in ("eq", "minus", "plus") for f in forms]
    M = np.array([[cells[b][k] for k in keys] for b in bases], dtype=float)
    idx = rng.integers(0, len(bases), size=(B, len(bases)))
    acc = {f"{p}/{f}": float(M[:, j].mean()) for j, (p, f) in enumerate(keys)}
    col = {k: j for j, k in enumerate(keys)}
    out = {"n_base": len(bases), "accuracy": acc, "did": {}, "valid": {}}
    for f in forms:
        if f == "same":
            continue
        d = (M[:, col[("eq", f)]] - M[:, col[("eq", "same")]]) - (M[:, col[("plus", f)]] - M[:, col[("plus", "same")]])
        boots = d[idx].mean(axis=1)
        out["did"][f] = {"estimate": float(d.mean()), "ci95": [float(np.percentile(boots, 2.5)),
                                                                float(np.percentile(boots, 97.5))]}
        out["valid"][f] = bool(acc[f"plus/{f}"] >= 0.70 and acc[f"minus/{f}"] >= 0.70)
    return out


def verdict(s: dict, kind: str) -> dict:
    a, did = s["accuracy"], s["did"]
    v = {}
    v["H_span"] = bool(a["eq/same"] < 0.6 and all(did[f]["estimate"] >= 0.20 for f in did))
    if kind == "date":
        v["H_token"] = bool(did["words"]["estimate"] >= 0.20 and did["reorder"]["estimate"] < 0.10)
    v["H_strict"] = bool(all(did[f]["estimate"] < 0.10 for f in did) and
                         all(a[k] >= 0.8 for k in a if k.split("/")[0] in ("minus", "plus")))
    v["H_approx"] = bool(a["minus/same"] < 0.7)
    return v


def main():
    rng = np.random.default_rng(SEED)
    results = {}
    lines = ["# Pilot 1 tables (generated by `project_anomaly/scripts/analyze_pilot1.py`)", "",
             "Accuracy by position/form; DiD with 95% bootstrap CI over base cases; `valid` = plus and minus accuracy "
             "≥ 0.70 in that form. Families pooled, then by family.", ""]
    for model in CHECKPOINTS:
        correct = table(model)
        results[model] = {}
        for kind in ("threshold", "date"):
            pooled = {}
            for (k, fam), cells in correct.items():
                if k == kind:
                    pooled.update({f"{fam}:{b}": c for b, c in cells.items()})
            groups = {"pooled": pooled}
            if kind == "threshold":       # `reorder` exists only for research_funding; pool same/words over all
                groups["pooled"] = {b: {k: v for k, v in c.items() if k[1] != "reorder"} for b, c in pooled.items()}
            for (k, fam), cells in sorted(correct.items()):
                if k == kind:
                    groups[fam] = dict(cells)
            results[model][kind] = {}
            for g, cells in groups.items():
                s = summarise(cells, rng)
                if g == "pooled":
                    s["verdict"] = verdict(s, kind)
                results[model][kind][g] = s
    json.dump(results, open(RES / "pilot1_results.json", "w", newline="\n"), indent=2)
    for model, byk in results.items():
        lines += [f"## {model}", ""]
        for kind, byg in byk.items():
            lines += [f"### {kind}", "", "| group | n | eq/same | eq/reorder | eq/words | minus/same | minus/reorder | "
                      "minus/words | plus/same | plus/reorder | plus/words | DiD reorder | DiD words | valid |",
                      "|" + "---|" * 14]
            for g, s in byg.items():
                a = s["accuracy"]
                cell = lambda k: f"{a[k]:.2f}" if k in a else "–"  # noqa: E731
                dd = lambda f: (f"{s['did'][f]['estimate']:+.2f} [{s['did'][f]['ci95'][0]:+.2f}, "  # noqa: E731
                                f"{s['did'][f]['ci95'][1]:+.2f}]") if f in s["did"] else "–"
                lines.append(f"| {g} | {s['n_base']} | " + " | ".join(cell(f"{p}/{f}") for p in ("eq", "minus", "plus")
                             for f in ("same", "reorder", "words")) + f" | {dd('reorder')} | {dd('words')} | "
                             + ", ".join(f"{f}:{'yes' if ok else 'no'}" for f, ok in s["valid"].items()) + " |")
            lines += ["", "Verdict (pooled): " + ", ".join(f"{h}={'supported' if x else 'not supported'}"
                                                          for h, x in byg["pooled"]["verdict"].items()), ""]
    (RES / "PILOT1_TABLES.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
