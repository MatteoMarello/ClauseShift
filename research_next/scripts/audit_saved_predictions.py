"""Exploratory audit of existing ClauseShift results (saved predictions only; no model is run).

Questions (research_next/SCIENTIFIC_AUDIT.md):
  A1  Are flip-pair errors explained by document length, number of conditions or evidence position?
  A2  Is the cross-reference result explained by complexity (matched comparison with exception_add)?
  A3  Exact boundaries: do errors mean "treated the strict cutoff as satisfied"? Family / number format?
  A4  Label bias of errors on the hardest operators.
  A5  Family difficulty: per-family and per-operator accuracy of fine-tuned groups (dev vs test families).
  A6  Lexical shortcut availability: is the cross-reference label decidable from the article number alone?

Writes research_next/results/audit.json and research_next/results/AUDIT_TABLES.md. Exploratory: these analyses
were not preregistered and were run after the original results were known.
"""

import collections
import functools
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "src"))

import numpy as np  # noqa: E402

from clauseshift.data import load  # noqa: E402
from clauseshift.domains import DOMAINS  # noqa: E402
from clauseshift.generator import OPERATORS_FLIP  # noqa: E402

PRED = ROOT / "results" / "predictions"
OUT = ROOT / "research_next" / "results"
OUT.mkdir(parents=True, exist_ok=True)
RNG = np.random.default_rng(0)
COND = ("threshold", "date", "scope", "exception", "xref")

data = {s: load(s, ROOT / "data") for s in ("dev", "test")}


@functools.lru_cache(maxsize=None)
def preds(system: str, split: str) -> dict[str, str]:
    with open(PRED / system / f"{split}.jsonl", encoding="utf-8") as f:
        return {r["id"]: r["pred"] for r in map(json.loads, f)}


def groups() -> dict[str, list[str]]:
    g = collections.defaultdict(list)
    for d in sorted(PRED.iterdir()):
        if not (d / "test.jsonl").exists():
            continue
        g[re.sub(r"_s\d+$", "", d.name)].append(d.name)
    return dict(g)


G = groups()
UNITS = ["zeroshot_nli-deberta-v3-base", "zeroshot_DeBERTa-v3-base-mnli-fever-anli",
         "ft_nli-deberta-v3-xsmall_paired", "ft_nli-deberta-v3-xsmall_unpaired",
         "ft_nli-deberta-v3-xsmall_op_holdout", "ft_deberta-v3-xsmall_paired", "ft_deberta-v3-xsmall_unpaired"]


def pairs(split: str) -> dict[str, dict]:
    out = collections.defaultdict(dict)
    for it in data[split]:
        out[it["pair_id"]][it["side"]] = it
    return out


def ci(x: np.ndarray, b: int = 2000) -> tuple[float, float, float]:
    if len(x) == 0:
        return float("nan"), float("nan"), float("nan")
    bs = [x[RNG.integers(0, len(x), len(x))].mean() for _ in range(b)]
    return float(x.mean()), float(np.percentile(bs, 2.5)), float(np.percentile(bs, 97.5))


def fmt(t) -> str:
    return f"{t[0]:.3f} [{t[1]:.3f}, {t[2]:.3f}]"


res, L = {}, ["# Audit tables (exploratory; generated by research_next/scripts/audit_saved_predictions.py)", ""]
P = pairs("test")
flip_pairs = {k: v for k, v in P.items() if v["A"]["operator_class"] == "flip"}


def pair_feats(p: dict) -> dict:
    a, b = p["A"], p["B"]
    n_sent = (len(a["sentences"]) + len(b["sentences"])) / 2
    n_cond = (sum(r in COND for r in a["sentence_roles"]) + sum(r in COND for r in b["sentence_roles"])) / 2
    n_char = (len(a["premise"]) + len(b["premise"])) / 2
    # position of the edited sentence (relative index in the longer document); -1 if no single edited sentence
    long_, short = (a, b) if len(a["sentences"]) >= len(b["sentences"]) else (b, a)
    diff = [k for k, s in enumerate(long_["sentences"]) if s not in short["sentences"]]
    pos = diff[0] / max(len(long_["sentences"]) - 1, 1) if diff else float("nan")
    return {"n_sent": n_sent, "n_cond": n_cond, "n_char": n_char, "edit_pos": pos}


feats = {k: pair_feats(v) for k, v in flip_pairs.items()}

# ---------------- A1: covariates of flip-pair success -----------------------------------------
L += ["## A1. Flip-pair accuracy by document complexity and edit position (test, flip pairs)", "",
      "Seeds pooled within a group. Terciles are computed over all flip pairs. 95% bootstrap intervals over pairs.", ""]
res["A1"] = {}
for var in ("n_cond", "n_char", "edit_pos"):
    vals = np.array([feats[k][var] for k in flip_pairs])
    ok = ~np.isnan(vals)
    cuts = np.nanpercentile(vals, [33.3, 66.7])
    L += [f"**{var}** (tercile cut points {cuts[0]:.2f}, {cuts[1]:.2f})", "",
          "| Unit | low | mid | high |", "|---|---|---|---|"]
    res["A1"][var] = {}
    for u in UNITS:
        row = []
        for lo, hi in ((-np.inf, cuts[0]), (cuts[0], cuts[1]), (cuts[1], np.inf)):
            sel = [k for k in flip_pairs if ok[list(flip_pairs).index(k)] and lo < feats[k][var] <= hi]
            x = np.array([preds(m, "test")[flip_pairs[k]["A"]["id"]] == flip_pairs[k]["A"]["label"] and
                          preds(m, "test")[flip_pairs[k]["B"]["id"]] == flip_pairs[k]["B"]["label"]
                          for m in G[u] for k in sel], float)
            row.append(ci(x))
        res["A1"][var][u] = row
        L.append(f"| {u} | " + " | ".join(fmt(t) for t in row) + " |")
    L.append("")

# Within-operator check: does complexity predict success *inside* an operator? (removes operator confound)
L += ["**Within-operator association** (mean over flip operators of: accuracy on pairs above the operator's median "
      "number of conditions − accuracy at or below it; seeds pooled)", "", "| Unit | Δ (more conditions − fewer) |",
      "|---|---|"]
res["A1"]["within_operator_n_cond"] = {}
for u in UNITS:
    deltas = []
    for op in OPERATORS_FLIP:
        ks = [k for k in flip_pairs if flip_pairs[k]["A"]["operator"] == op]
        med = np.median([feats[k]["n_cond"] for k in ks])
        hi = [k for k in ks if feats[k]["n_cond"] > med]
        lo = [k for k in ks if feats[k]["n_cond"] <= med]
        if len(hi) < 10 or len(lo) < 10:
            continue

        def acc(sel):
            return np.mean([preds(m, "test")[flip_pairs[k]["A"]["id"]] == flip_pairs[k]["A"]["label"] and
                            preds(m, "test")[flip_pairs[k]["B"]["id"]] == flip_pairs[k]["B"]["label"]
                            for m in G[u] for k in sel])
        deltas.append(acc(hi) - acc(lo))
    res["A1"]["within_operator_n_cond"][u] = float(np.mean(deltas))
    L.append(f"| {u} | {np.mean(deltas):+.3f} (over {len(deltas)} operators) |")
L.append("")

# ---------------- A2: cross-reference vs inline exemption at matched complexity --------------------------
L += ["## A2. Cross-reference vs. inline exemption, matched on number of sentences (test)", "",
      "Pairs of `xref_redirect` and `exception_add` are grouped by their mean number of sentences (rounded); the "
      "comparison uses only sentence counts that occur in both operators, weighting by xref pair counts.", ""]
res["A2"] = {}
L += ["| Unit | exception_add (matched) | xref_redirect | Difference |", "|---|---|---|---|"]
for u in UNITS:
    by = collections.defaultdict(lambda: {"exception_add": [], "xref_redirect": []})
    for k, p in flip_pairs.items():
        op = p["A"]["operator"]
        if op in ("exception_add", "xref_redirect"):
            for m in G[u]:
                pr = preds(m, "test")
                by[round(feats[k]["n_sent"])][op].append(
                    pr[p["A"]["id"]] == p["A"]["label"] and pr[p["B"]["id"]] == p["B"]["label"])
    common = [n for n in by if by[n]["exception_add"] and by[n]["xref_redirect"]]
    w = np.array([len(by[n]["xref_redirect"]) for n in common], float)
    ex = np.array([np.mean(by[n]["exception_add"]) for n in common])
    xr = np.array([np.mean(by[n]["xref_redirect"]) for n in common])
    e, x = float((w * ex).sum() / w.sum()), float((w * xr).sum() / w.sum())
    res["A2"][u] = {"exception_matched": e, "xref": x, "sentence_counts": sorted(common)}
    L.append(f"| {u} | {e:.3f} | {x:.3f} | {x - e:+.3f} |")
L.append("")

# ---------------- A3: exact boundary items ------------------------------------------------------
L += ["## A3. Exact-boundary items (threshold_cross, date_cross; test)", "",
      "Boundary side: the case value equals the cutoff (\"more than 50\" with 50; \"after 3 May\" with 3 May), so "
      "the condition fails. An error that reproduces the label of the other side of the pair (where the condition "
      "is satisfied) means the strict comparison was read as non-strict.", ""]


def boundary_side(p: dict) -> str | None:
    for s in ("A", "B"):
        it = p[s]
        if it["operator"] == "threshold_cross":
            m = re.search(r"(€[\d,]+|\b\d+\b(?= (?:credits|years|items|employees)))", it["hypothesis"])
            if m and re.search(re.escape(m.group(1)) + r"(?![\d,])", it["premise"]):
                return s
        if it["operator"] == "date_cross":
            m = re.search(r"(\d{1,2} [A-Z][a-z]+ \d{4})", it["hypothesis"])
            if m and m.group(1) in it["premise"]:
                return s
    return None


bpairs = {k: (p, boundary_side(p)) for k, p in flip_pairs.items()
          if p["A"]["operator"] in ("threshold_cross", "date_cross") and boundary_side(p)}
L += [f"Boundary pairs found: {len(bpairs)} "
      f"(threshold {sum(p['A']['operator'] == 'threshold_cross' for p, _ in bpairs.values())}, "
      f"date {sum(p['A']['operator'] == 'date_cross' for p, _ in bpairs.values())}).", "",
      "| Unit | Boundary side correct | Errors that copy the satisfied side's label | Non-boundary flip pairs of same operators: other side correct |",
      "|---|---|---|---|"]
res["A3"] = {}
for u in UNITS:
    corr, copy, nonb = [], [], []
    for k, (p, s) in bpairs.items():
        o = "B" if s == "A" else "A"
        for m in G[u]:
            pr = preds(m, "test")
            c = pr[p[s]["id"]] == p[s]["label"]
            corr.append(c)
            if not c:
                copy.append(pr[p[s]["id"]] == p[o]["label"])
            nonb.append(pr[p[o]["id"]] == p[o]["label"])
    res["A3"][u] = {"boundary_correct": ci(np.array(corr, float)), "errors_copy_satisfied": ci(np.array(copy, float)),
                    "n_errors": len(copy), "other_side_correct": ci(np.array(nonb, float))}
    L.append(f"| {u} | {fmt(res['A3'][u]['boundary_correct'])} | {fmt(res['A3'][u]['errors_copy_satisfied'])} "
             f"(n={len(copy)}) | {fmt(res['A3'][u]['other_side_correct'])} |")
L.append("")
L += ["Threshold flip-pair accuracy by test family (number format differs: credits as plain integers in enrollment, "
      "budgets as €-amounts with thousands separators in research_funding):", "",
      "| Unit | enrollment threshold_cross | research_funding threshold_cross | enrollment date_cross | research_funding date_cross |",
      "|---|---|---|---|---|"]
res["A3"]["by_family"] = {}
for u in UNITS:
    row = []
    for op in ("threshold_cross", "date_cross"):
        for fam in ("enrollment", "research_funding"):
            x = np.array([preds(m, "test")[p["A"]["id"]] == p["A"]["label"] and
                          preds(m, "test")[p["B"]["id"]] == p["B"]["label"]
                          for m in G[u] for p in flip_pairs.values()
                          if p["A"]["operator"] == op and p["A"]["family"] == fam], float)
            row.append(ci(x))
    res["A3"]["by_family"][u] = row
    L.append(f"| {u} | " + " | ".join(fmt(row[i]) for i in (0, 2, 1, 3)) + " |")
L.append("")

# ---------------- A4: label of errors on hard operators ---------------------------------------------
L += ["## A4. Predicted label on wrong items, hard operators (test; seeds pooled)", "",
      "| Unit | Operator | n errors | → entailed | → contradicted | → insufficient |", "|---|---|---|---|---|---|"]
res["A4"] = {}
for u in UNITS:
    for op in ("threshold_cross", "date_cross", "scope_restrict", "xref_redirect"):
        errs = collections.Counter()
        for m in G[u]:
            pr = preds(m, "test")
            for it in data["test"]:
                if it["operator"] == op and pr[it["id"]] != it["label"]:
                    errs[pr[it["id"]]] += 1
        n = sum(errs.values())
        res["A4"][f"{u}|{op}"] = dict(errs)
        if n:
            L.append(f"| {u} | {op} | {n} | " + " | ".join(f"{errs[l] / n:.2f}" for l in
                                                            ("entailed", "contradicted", "insufficient")) + " |")
L.append("")

# ---------------- A5: family difficulty -------------------------------------------------------------
L += ["## A5. Item accuracy by family and operator class (fine-tuned groups; dev = vehicles)", "",
      "| Unit | vehicles (dev) | enrollment | research_funding | vehicles, flip pairs | enrollment, flip pairs | research_funding, flip pairs |",
      "|---|---|---|---|---|---|---|"]
res["A5"] = {}
for u in [x for x in UNITS if x.startswith("ft_")]:
    row = []
    for split, fam in (("dev", "vehicles"), ("test", "enrollment"), ("test", "research_funding")):
        x = np.array([preds(m, split)[i["id"]] == i["label"] for m in G[u] for i in data[split] if i["family"] == fam], float)
        row.append(ci(x))
    for split, fam in (("dev", "vehicles"), ("test", "enrollment"), ("test", "research_funding")):
        PP = pairs(split)
        x = np.array([preds(m, split)[p["A"]["id"]] == p["A"]["label"] and preds(m, split)[p["B"]["id"]] == p["B"]["label"]
                      for m in G[u] for p in PP.values() if p["A"]["family"] == fam and p["A"]["operator_class"] == "flip"], float)
        row.append(ci(x))
    res["A5"][u] = row
    L.append(f"| {u} | " + " | ".join(fmt(t) for t in row) + " |")
L.append("")

# ---------------- A6: shortcut availability for cross-references ----------------------------------
L += ["## A6. Is the cross-reference label decidable from the article number alone? (all splits)", ""]
alls = load("train", ROOT / "data") + data["dev"] + data["test"]
rows, cat_same = collections.Counter(), collections.Counter()
for it in alls:
    if "xref" not in it["sentence_roles"]:
        continue
    s = it["sentences"][it["sentence_roles"].index("xref")]
    dom = DOMAINS[it["family"]]
    case_cat = [pl for a, pl in dom["categories"] if f" is {a}." in it["hypothesis"]]
    cat_same[bool(case_cat) and case_cat[0].lower() in s.lower()] += 1
    neg_claim = bool(re.search(r"is not required to|does not have to|has no obligation to", it["hypothesis"]))
    rows[("Article 1" in s, neg_claim, it["label"])] += 1
res["A6"] = {"xref_items": sum(cat_same.values()), "xref_names_case_category": cat_same[True],
             "xref_sentences_outside_xref_redirect": sum(1 for it in alls if "xref" in it["sentence_roles"]
                                                         and it["operator"] != "xref_redirect"),
             "table": {f"{k}": v for k, v in rows.items()}}
L += [f"Items containing a cross-reference sentence: {sum(cat_same.values())}; of these, naming the case's own "
      f"category: {cat_same[True]}; cross-reference sentences outside `xref_redirect` pairs: "
      f"{res['A6']['xref_sentences_outside_xref_redirect']}.", "",
      "| Refers to Article 1 | Negative claim | Gold label | Items |", "|---|---|---|---|"]
for (a1, neg, lab), n in sorted(rows.items()):
    L.append(f"| {a1} | {neg} | {lab} | {n} |")
L += ["", "If the label is a deterministic function of (refers to Article 1, claim polarity), a model can solve every "
      "cross-reference item without checking the category or resolving the reference.", ""]

(OUT / "audit.json").write_text(json.dumps(res, indent=1, default=float), encoding="utf-8")
(OUT / "AUDIT_TABLES.md").write_text("\n".join(L) + "\n", encoding="utf-8")
print("\n".join(L))
