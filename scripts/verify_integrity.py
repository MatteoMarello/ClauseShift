"""Non-destructive integrity check of data, predictions and reported metrics.

1. Regenerates the dataset in memory (nothing is written) and compares content hashes with data/manifest.json
   and with the files on disk; re-runs the integrity checks of clauseshift.data.check on the files on disk.
2. Checks that every prediction file covers exactly the ids of its split, with valid labels and normalised
   probabilities, and that `pred` is the arg-max of `probs`.
3. Recomputes the point estimates of every system in results/summary.json from the prediction files.

Writes results/INTEGRITY.md and exits with status 1 on any failure.
"""

import json
import math
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

from clauseshift.data import build, check, load  # noqa: E402
from clauseshift.generator import LABELS, content_hash  # noqa: E402
from clauseshift.metrics import group_pairs, pair_metrics  # noqa: E402
from clauseshift.predictions import ROOT, load_predictions  # noqa: E402

failures, lines = [], ["# Integrity report (generated by scripts/verify_integrity.py)", ""]


def ok(cond: bool, msg: str) -> None:
    lines.append(f"- {'PASS' if cond else 'FAIL'}: {msg}")
    if not cond:
        failures.append(msg)


# 1. data
manifest = json.loads(Path("data/manifest.json").read_text())
config = json.loads(Path("configs/data.json").read_text())
rebuilt = build(config)
on_disk = {s: load(s) for s in ("train", "dev", "test")}
lines += ["## Data", ""]
for s in ("train", "dev", "test"):
    h_manifest = manifest["files"][s]["sha256_content"]
    ok(content_hash(on_disk[s]) == h_manifest, f"{s}: file content hash matches manifest ({h_manifest[:12]}…)")
    ok(content_hash(rebuilt[s]) == h_manifest, f"{s}: in-memory regeneration matches manifest")
try:
    check(on_disk)
    ok(True, "integrity checks (pairs, label relations, disjoint families, duplicates, reserved templates)")
except AssertionError as e:
    ok(False, f"integrity checks: {e}")

# 2. predictions
lines += ["", "## Prediction files", ""]
ids = {s: {i["id"] for i in on_disk[s]} for s in ("dev", "test")}
systems = sorted(d.name for d in ROOT.iterdir() if (d / "test.jsonl").exists())
for sysname in systems:
    for s in ("dev", "test"):
        if not (ROOT / sysname / f"{s}.jsonl").exists():
            continue
        P = load_predictions(sysname, s)
        cover = set(P) == ids[s]
        valid = all(r["pred"] in LABELS and set(r["probs"]) == set(LABELS) for r in P.values())
        norm = all(abs(sum(r["probs"].values()) - 1) < 1e-3 for r in P.values())
        argmax = all(max(r["probs"], key=r["probs"].get) == r["pred"] for r in P.values())
        ok(cover and valid and norm and argmax, f"{sysname}/{s}: {len(P)} items, ids/labels/probabilities/arg-max")

# 3. summary.json point estimates
lines += ["", "## Reported metrics (results/summary.json)", ""]
summary = json.loads(Path("results/summary.json").read_text())
for sysname, rec in summary["systems"].items():
    if not (ROOT / sysname / "test.jsonl").exists():
        ok(False, f"{sysname}: listed in summary.json but prediction file is missing")
        continue
    preds = {k: v["pred"] for k, v in load_predictions(sysname, "test").items()}
    m = pair_metrics(group_pairs(on_disk["test"], preds))
    diffs = [k for k, v in rec["test"].items() if not math.isclose(v["point"], m[k], abs_tol=1e-9)]
    ok(not diffs, f"{sysname}: test point estimates reproduced" + (f" (mismatch: {diffs})" if diffs else ""))

lines += ["", f"**{'ALL CHECKS PASSED' if not failures else f'{len(failures)} FAILURE(S)'}**"]
Path("results/INTEGRITY.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
print("\n".join(lines))
sys.exit(1 if failures else 0)
