"""Exploratory error analysis (not preregistered): confusion matrices, boundary edits, calibration, examples.

Writes results/ERROR_ANALYSIS.md.
"""

import collections
import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

import numpy as np  # noqa: E402

from clauseshift.data import load  # noqa: E402
from clauseshift.generator import LABELS  # noqa: E402
from clauseshift.predictions import ROOT, load_predictions  # noqa: E402

test = load("test")
by_id = {i["id"]: i for i in test}
systems = [d.name for d in sorted(ROOT.iterdir()) if (d / "test.jsonl").exists()]


def is_boundary(item: dict) -> bool:
    """Threshold/date edits where the case value equals the cutoff (strict comparisons fail)."""
    if item["operator"] == "threshold_cross":
        m = re.search(r"(€[\d,]+|\b\d+ (?:credits|years)\b|\b\d+ items\b)", item["hypothesis"])
        return bool(m) and m.group(1).split()[0] in item["premise"]
    if item["operator"] == "date_cross":
        m = re.search(r"(\d{1,2} [A-Z][a-z]+ \d{4})", item["hypothesis"])
        return bool(m) and m.group(1) in item["premise"]
    return False


def ece(probs: list[dict], gold: list[str], bins: int = 10) -> float:
    conf = np.array([max(p.values()) for p in probs])
    corr = np.array([max(p, key=p.get) == g for p, g in zip(probs, gold)])
    edges = np.linspace(0, 1, bins + 1)
    e = 0.0
    for lo, hi in zip(edges[:-1], edges[1:]):
        m = (conf > lo) & (conf <= hi)
        if m.any():
            e += m.mean() * abs(corr[m].mean() - conf[m].mean())
    return float(e)


L = ["# Error analysis (exploratory; generated by scripts/error_analysis.py)", ""]
L += ["## Confusion matrices (test; rows = gold, columns = predicted)", ""]
for s in systems:
    P = load_predictions(s, "test")
    cm = collections.Counter((by_id[k]["label"], v["pred"]) for k, v in P.items())
    L += [f"**{s}**", "", "| gold \\ pred | " + " | ".join(LABELS) + " |", "|---|---|---|---|"]
    for g in LABELS:
        L.append(f"| {g} | " + " | ".join(str(cm[(g, p)]) for p in LABELS) + " |")
    L.append("")

L += ["## Exact-boundary edits (threshold_cross, date_cross)", "",
      "Item accuracy on the side of the pair whose case value equals the cutoff (\"more than 50\" with value 50) "
      "versus the other boundary-free items of the same operators.", "",
      "| System | Boundary items | Accuracy (boundary) | Accuracy (non-boundary) |", "|---|---|---|---|"]
for s in systems:
    P = load_predictions(s, "test")
    items = [i for i in test if i["operator"] in ("threshold_cross", "date_cross")]
    b = [P[i["id"]]["pred"] == i["label"] for i in items if is_boundary(i)]
    nb = [P[i["id"]]["pred"] == i["label"] for i in items if not is_boundary(i)]
    L.append(f"| {s} | {len(b)} | {np.mean(b):.3f} | {np.mean(nb):.3f} |")

L += ["", "## Calibration (test, 10-bin ECE)", "", "| System | ECE | Mean confidence | Accuracy |", "|---|---|---|---|"]
for s in systems:
    if s in ("majority",):
        continue
    P = load_predictions(s, "test")
    probs = [P[i["id"]]["probs"] for i in test]
    gold = [i["label"] for i in test]
    acc = np.mean([max(p, key=p.get) == g for p, g in zip(probs, gold)])
    L.append(f"| {s} | {ece(probs, gold):.3f} | {np.mean([max(p.values()) for p in probs]):.3f} | {acc:.3f} |")

# Examples: flip pairs the best fine-tuned group gets wrong on one side
ft = [s for s in systems if s.startswith("ft_") and "_paired_" in s]
if ft:
    s = sorted(ft)[0]
    P = load_predictions(s, "test")
    L += ["", f"## Example failures ({s})", ""]
    shown = collections.Counter()
    for i in test:
        if i["operator_class"] == "flip" and P[i["id"]]["pred"] != i["label"] and shown[i["operator"]] < 1:
            shown[i["operator"]] += 1
            L += [f"- **{i['operator']}** gold `{i['label']}`, predicted `{P[i['id']]['pred']}`",
                  f"  - Document: {i['premise']}", f"  - Hypothesis: {i['hypothesis']}"]
Path("results/ERROR_ANALYSIS.md").write_text("\n".join(L) + "\n", encoding="utf-8")
print("\n".join(L[:60]))
